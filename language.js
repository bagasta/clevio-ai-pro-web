const languageButtons = [...document.querySelectorAll('[data-language]')];
const originalTitle = document.title;
const description = document.querySelector('meta[name="description"]');
const originalDescription = description.content;
const sourceText = [];
const sourceAttributes = [];
const textWalker = document.createTreeWalker(document.body, NodeFilter.SHOW_TEXT);
while (textWalker.nextNode()) {
  const node = textWalker.currentNode;
  if (node.parentElement.closest('script, style, [data-language]')) continue;
  const key = node.nodeValue.trim();
  if (Object.hasOwn(englishCopy, key)) sourceText.push({ node, original: node.nodeValue, key });
}
document.querySelectorAll('[aria-label], img[alt]').forEach((element) => {
  if (element.matches('[data-language], .menu-toggle')) return;
  for (const attribute of ['aria-label', 'alt']) {
    const original = element.getAttribute(attribute);
    if (Object.hasOwn(englishCopy, original)) sourceAttributes.push({ element, attribute, original });
  }
});

function setLanguage(language) {
  if (language !== 'id' && language !== 'en') return;
  const english = language === 'en';
  document.documentElement.lang = language;
  sourceText.forEach(({ node, original, key }) => {
    node.nodeValue = english ? original.replace(key, englishCopy[key]) : original;
  });
  sourceAttributes.forEach(({ element, attribute, original }) => {
    element.setAttribute(attribute, english ? englishCopy[original] : original);
  });
  document.title = english ? 'Clevio AI Pro | Lead with AI. Create lasting value.' : originalTitle;
  description.content = english
    ? 'A one-day workshop for leaders and professionals to develop strategic thinking, put AI to work and create value for their organisations.'
    : originalDescription;
  languageButtons.forEach((button) => button.setAttribute('aria-pressed', String(button.dataset.language === language)));
  const menuButton = document.querySelector('.menu-toggle');
  const open = menuButton.getAttribute('aria-expanded') === 'true';
  menuButton.setAttribute('aria-label', english ? (open ? 'Close menu' : 'Open menu') : (open ? 'Tutup menu' : 'Buka menu'));
  try { localStorage.setItem('clevio-language', language); } catch { /* Storage may be disabled. */ }
  document.dispatchEvent(new Event('languagechange'));
}
languageButtons.forEach((button) => button.addEventListener('click', () => setLanguage(button.dataset.language)));
let savedLanguage = 'id';
try { savedLanguage = localStorage.getItem('clevio-language') || 'id'; } catch { /* Keep the Indonesian default. */ }
setLanguage(savedLanguage);
